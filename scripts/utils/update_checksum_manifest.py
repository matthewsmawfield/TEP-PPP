#!/usr/bin/env python3
"""Refresh the results checksum ledger.

Re-hashes every tracked file in ``results/checksum_manifest.json``, folds
in newly committed ``results/outputs/*.json`` and ``results/figures/*.png``
artifacts, and keeps the volatile live-audit products excluded (their
fresh generated timestamps would leave a pinned hash permanently stale
by design).  Writes both ``results/checksum_manifest.json`` (with
per-file metadata) and the flat ``results/checksums_sha256.json`` map.
"""

from __future__ import annotations

import datetime as _dt
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = ROOT / "results" / "checksum_manifest.json"
FLAT = ROOT / "results" / "checksums_sha256.json"

VOLATILE = {
    # regenerated by scripts/verify_manuscript.py (evidence_audit) or
    # scripts/live/*.py live-audit refreshers — a pinned hash is stale
    # by design on every refresh.
    "results/outputs/evidence_audit.json",
    "results/outputs/live_observatory_audit.json",
    "results/outputs/step_174_live_ledger.json",
    "results/outputs/sealed_anchor_chain_status.json",
    "results/outputs/sealed_lattice_audit.json",
}


def _sha256(p: Path) -> str:
    h = hashlib.sha256()
    with p.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main() -> int:
    manifest = json.loads(MANIFEST.read_text())
    files = set(manifest["files"])

    # Committed artifacts on disk join the ledger; volatile products are
    # managed through ``excluded_volatile`` instead.
    for p in sorted((ROOT / "results" / "outputs").glob("*.json")):
        files.add(p.relative_to(ROOT).as_posix())
    for p in sorted((ROOT / "results" / "figures").glob("*.png")):
        files.add(p.relative_to(ROOT).as_posix())
    files -= VOLATILE

    entries = {}
    missing = []
    for rel in sorted(files):
        p = ROOT / rel
        if not p.exists():
            missing.append(rel)
            continue
        st = p.stat()
        entries[rel] = {
            "sha256": _sha256(p),
            "size_bytes": st.st_size,
            "modified": _dt.datetime.fromtimestamp(st.st_mtime).isoformat(
                timespec="seconds"),
        }
    for rel in missing:
        print(f"WARNING: tracked file missing, dropped: {rel}")

    manifest["generated"] = _dt.datetime.now(
        _dt.timezone.utc).isoformat()
    manifest["files"] = entries
    manifest["excluded_volatile"] = sorted(VOLATILE)
    MANIFEST.write_text(json.dumps(manifest, indent=2) + "\n")
    FLAT.write_text(json.dumps(
        {rel: e["sha256"] for rel, e in entries.items()},
        indent=2) + "\n")
    print(f"checksummed {len(entries)} files -> {MANIFEST.name}, "
          f"{FLAT.name}; {len(VOLATILE)} volatile excluded")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
